-- Extras gallery generator (WM15c). Prepare & Check runs it beside music sync.
-- Reads the PNGs in developer/assets/extras/ and writes two files:
--   developer/ui/menus/extras_gallery.atlas            one image per PNG, sorted
--   developer/config/extras_gallery_generated.lua      {images={[stem]={width=,height=}}}
-- An empty folder writes the placeholder image, so the atlas always builds.
-- Pure and LuaJ-safe: no frontier patterns, precision formats or quoting formats.
-- The editor supplies list_dir_filesystem, read_head and write_if_changed.
local M = {}

M.DIR = "developer/assets/extras"
M.ATLAS_PATH = "developer/ui/menus/extras_gallery.atlas"
M.GENERATED_PATH = "developer/config/extras_gallery_generated.lua"
M.PLACEHOLDER = "/builtins/graphics/particle_blob.png"
-- An atlas without Max Page Size is one texture: keep each side and the total small enough.
M.MAX_SIDE = 4096
M.WARN_PIXELS = 16000000

local PNG_SIGNATURE = "\137PNG\r\n\26\n"

-- Width and height from the first 24 bytes of a PNG (signature, IHDR length,
-- "IHDR", then big-endian width and height), or nil.
function M.png_size(header)
    if type(header) ~= "string" or #header < 24 or header:sub(1, 8) ~= PNG_SIGNATURE
        or header:sub(13, 16) ~= "IHDR" then
        return nil
    end
    local function int(offset)
        local b1, b2, b3, b4 = header:byte(offset, offset + 3)
        return b1 * 16777216 + b2 * 65536 + b3 * 256 + b4
    end
    local width, height = int(17), int(21)
    if width <= 0 or height <= 0 then return nil end
    return width, height
end

-- The image name a creator writes in extras.lua: the file name without .png.
-- Only letters, digits, "_" and "-" are accepted, so the name is also a safe
-- atlas animation id and Lua table key.
function M.stem(name)
    if type(name) ~= "string" then return nil end
    local stem = name:match("^(.+)%.[Pp][Nn][Gg]$")
    if not stem or not stem:match("^[%w_%-]+$") then return nil end
    return stem
end

local function atlas_text(stems)
    local lines = {}
    if #stems == 0 then
        lines[#lines + 1] = "images {\n  image: \"" .. M.PLACEHOLDER .. "\"\n}"
    else
        for _, entry in ipairs(stems) do
            lines[#lines + 1] = "images {\n  image: \"/" .. M.DIR .. "/" .. entry.file .. "\"\n}"
        end
    end
    lines[#lines + 1] = "extrude_borders: 2"
    return table.concat(lines, "\n") .. "\n"
end

local function generated_text(stems)
    local lines = {
        "-- GENERATED by Project > Prepare & Check from developer/assets/extras/. Do not edit.",
        "-- Each key is a PNG name without .png; gallery entries in extras.lua name it as `image`.",
        "return {",
        "    images = {",
    }
    for _, entry in ipairs(stems) do
        lines[#lines + 1] = "        [\"" .. entry.stem .. "\"] = { width = " .. tostring(entry.width)
            .. ", height = " .. tostring(entry.height) .. " },"
    end
    lines[#lines + 1] = "    },"
    lines[#lines + 1] = "}"
    return table.concat(lines, "\n") .. "\n"
end

-- files: array of {name=, header=} (header: at least the first 24 bytes).
-- Returns {atlas=, generated=, images={[stem]={width=,height=}}, errors={}, warnings={}}.
-- An error leaves its image out; the caller decides whether errors stop preparation.
function M.build(files)
    local errors, warnings, entries, by_stem = {}, {}, {}, {}
    local names = {}
    for _, file in ipairs(files or {}) do
        if type(file) == "table" and type(file.name) == "string" then names[#names + 1] = file end
    end
    table.sort(names, function(a, b) return a.name < b.name end)
    local total = 0
    for _, file in ipairs(names) do
        local where = M.DIR .. "/" .. file.name
        if file.name:match("%.[Pp][Nn][Gg]$") then
            local stem = M.stem(file.name)
            local width, height = M.png_size(file.header)
            if not stem then
                errors[#errors + 1] = where .. ": rename it with only letters, digits, _ and - before .png."
            elseif by_stem[stem:lower()] then
                errors[#errors + 1] = where .. ": another image is also named " .. stem .. "; rename one of them."
            elseif not width then
                errors[#errors + 1] = where .. ": not a readable PNG image."
            elseif width > M.MAX_SIDE or height > M.MAX_SIDE then
                errors[#errors + 1] = where .. ": " .. tostring(width) .. " x " .. tostring(height)
                    .. " pixels; each side must be " .. tostring(M.MAX_SIDE) .. " or less."
            else
                by_stem[stem:lower()] = true
                entries[#entries + 1] = { stem = stem, file = file.name, width = width, height = height }
                total = total + width * height
            end
        end
    end
    table.sort(entries, function(a, b) return a.stem < b.stem end)
    if total > M.WARN_PIXELS then
        warnings[#warnings + 1] = M.DIR .. ": the gallery holds " .. tostring(total)
            .. " pixels, more than 16 megapixels. Its texture stays in memory while Extras is open; use smaller images."
    end
    local images = {}
    for _, entry in ipairs(entries) do images[entry.stem] = { width = entry.width, height = entry.height } end
    return { atlas = atlas_text(entries), generated = generated_text(entries), images = images,
        errors = errors, warnings = warnings }
end

-- The committed empty state, also written by Reset Project to Empty.
function M.empty_files()
    local empty = M.build({})
    return {
        { path = M.ATLAS_PATH, content = empty.atlas },
        { path = M.GENERATED_PATH, content = empty.generated },
    }
end

local function join(root, rel)
    if root == nil or root == "" or root == "." then return rel end
    return (tostring(root):gsub("[/\\]+$", "")) .. "/" .. rel
end

-- deps: root, list_dir_filesystem(abs_dir) -> dirs, files; read_head(path, count)
-- -> the file's first count bytes or nil (mvtk/editor/file_utils.lua
-- read_binary_head: a PNG is never read in full); write_if_changed(path, text)
-- -> changed. Returns (true, summary) or (false, message).
-- summary: images (count), changed_files, errors, warnings.
function M.sync_core(deps)
    deps = deps or {}
    if type(deps.list_dir_filesystem) ~= "function" or type(deps.read_head) ~= "function"
        or type(deps.write_if_changed) ~= "function" then
        return false, "Extras gallery generator is missing an editor file function."
    end
    local listed_ok, _, names = pcall(deps.list_dir_filesystem, join(deps.root, M.DIR))
    if not listed_ok then names = {} end
    local files = {}
    for _, name in ipairs(names or {}) do
        if type(name) == "string" and name:match("%.[Pp][Nn][Gg]$") then
            local data = deps.read_head(join(deps.root, M.DIR .. "/" .. name), 24)
            files[#files + 1] = { name = name, header = type(data) == "string" and data:sub(1, 24) or nil }
        end
    end
    local result = M.build(files)
    local changed = {}
    for _, write in ipairs({ { M.ATLAS_PATH, result.atlas }, { M.GENERATED_PATH, result.generated } }) do
        local ok, value = pcall(deps.write_if_changed, join(deps.root, write[1]), write[2])
        if not ok then return false, "Could not write " .. write[1] .. ": " .. tostring(value) end
        if value then changed[#changed + 1] = write[1] end
    end
    local count = 0
    for _ in pairs(result.images) do count = count + 1 end
    return true, { images = count, changed_files = changed, errors = result.errors, warnings = result.warnings }
end

return M
