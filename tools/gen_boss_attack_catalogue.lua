-- Run from the repository root with Lua 5.1.
local Patterns = require "mvtk.bosses.patterns.attack_patterns"
local Scheduler = require "mvtk.bosses.attack_scheduler"
local Defaults = require "developer.config.boss_defaults"
local Schema = require "mvtk.bosses.attack_pattern_schema"
local M = {}

local no_distance_limit = {
    aoe = "player-targeted", buff = "boss effect", combo = "depends on the steps",
    dive = "tracks within the arena", environmental = "arena effect", hazard_pulse = "placed hazards",
    heal = "boss effect", leap = "arena anchor", mine = "placed at boss or player",
    parry_window = "counter stance", rain = "arena or room bounds", reposition = "arena anchor",
    shield = "boss effect", summon = "summons around the boss", zone = "player or arena anchor",
}

function M.render()
    local names = {}
    for name in pairs(Patterns) do names[#names + 1] = name end
    table.sort(names)
    local lines = {
        "<!-- Generated by `lua tools/gen_boss_attack_catalogue.lua`. -->",
        "# Boss attack catalogue",
        "",
        "Pick an attack by the space it covers and the warning it gives the player.",
        "Distances use the 64-pixel reference tile size. Reach is the pattern's distance before applying",
        "the boss's chase range. A moveset can set its own range. Floor attacks also check the player's height.",
        "Times are seconds of play across refresh rates. The warning column shows the opening warning.",
        "For a tracking beam it includes both the turn and the hold before the beam hurts.",
        "Other attacks can add a wind-up, a follow-up warning or travel time.",
        "",
        "To make your own pattern, see [Make a combo or a beam](CREATOR_WORKFLOW.html#make-a-combo-or-a-beam)",
        "and the [shipped patterns](../mvtk/bosses/patterns/attack_patterns.lua). Start with `sword_combo`",
        "or `berserk_whip` for several strikes, `laser_sweep` for a beam that turns across an arc,",
        "or `dark_beam` for one that follows the player and then holds its aim.",
        "For a floor slam, `vertical_clearance` is the height the player's feet must clear above the struck floor.",
        "",
        "| Pattern | Kind | Reach (px) | Warning (s) | Cooldown (s) | How to avoid it |",
        "| --- | --- | ---: | ---: | ---: | --- |",
    }
    for _, name in ipairs(names) do
        local pattern = Patterns[name]
        local reach = Scheduler.pattern_reach(pattern, 0, Defaults)
        local distance = reach and ("%g"):format(reach) or assert(no_distance_limit[pattern.type], name)
        if pattern.type == "combo" and reach == 0 then distance = "uses phase chase range" end
        local warning = pattern.telegraph_time
        if pattern.type == "beam" and pattern.beam and pattern.beam.track_time then
            warning = warning + assert(Schema.tracking_beam_windup(pattern, Defaults))
        end
        lines[#lines + 1] = ("| `%s` | `%s` | %s | %g | %g | %s |"):format(name, pattern.type,
            distance, warning, pattern.cooldown, assert(pattern.avoid, name))
    end
    return table.concat(lines, "\n") .. "\n"
end

if ... ~= "tools.gen_boss_attack_catalogue" then
    local file = assert(io.open("docs/BOSS_ATTACK_CATALOGUE.md", "wb"))
    assert(file:write(M.render()))
    assert(file:close())
end

return M
